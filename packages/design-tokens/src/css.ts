import {
  breakpoints,
  dark,
  light,
  motion,
  palette,
  radius,
  shadow,
  typography,
  type SemanticColors,
} from './tokens.js';

function paletteVariables(): string[] {
  const lines: string[] = [];
  for (const [name, value] of Object.entries(palette)) {
    if (typeof value === 'string') {
      lines.push(`  --color-${name}: ${value};`);
      continue;
    }
    for (const [shade, hex] of Object.entries(value)) {
      lines.push(`  --color-${name}-${shade}: ${hex};`);
    }
  }
  return lines;
}

function semanticBlock(selector: string, colors: SemanticColors, indent = ''): string {
  const body = Object.entries(colors)
    .map(([name, value]) => `${indent}  --rc-${name}: ${value};`)
    .join('\n');
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

const PIXELS_PER_REM = 16;
const SECTION_SEPARATOR = '\n\n';
const NESTED_INDENT = '  ';
const GENERATED_HEADER = '/* Generated by @rc/design-tokens. Do not edit. */';
const SCOPED_PREVIEWS_NOTE =
  '/* Scoped previews: any element can force a theme for its subtree, as the /design page does. */';
const COLOR_SCHEME_RULES = [
  ':root { color-scheme: light; }',
  ':root[data-theme="dark"], [data-theme="dark"] { color-scheme: dark; }',
  '[data-theme="light"] { color-scheme: light; }',
] as const;

function prefixedVariables(prefix: string, values: Readonly<Record<string, string | number>>): string[] {
  return Object.entries(values).map(([name, value]) => `  --${prefix}-${name}: ${value};`);
}

function breakpointVariables(): string[] {
  return Object.entries(breakpoints).map(
    ([name, pixels]) => `  --breakpoint-${name}: ${pixels / PIXELS_PER_REM}rem;`,
  );
}

function fontVariables(): string[] {
  return [`  --font-display: ${typography.display};`, `  --font-sans: ${typography.body};`];
}

function motionVariables(): string[] {
  return [
    `  --ease-brand: ${motion.ease};`,
    `  --duration-fast: ${motion.fast};`,
    `  --duration-base: ${motion.base};`,
    `  --duration-slow: ${motion.slow};`,
  ];
}

function themeBlock(): string {
  const lines = [
    ...paletteVariables(),
    ...fontVariables(),
    ...prefixedVariables('radius', radius),
    ...prefixedVariables('shadow', shadow),
    ...breakpointVariables(),
    ...motionVariables(),
  ];
  return `@theme {\n${lines.join('\n')}\n}`;
}

function semanticThemeBlock(): string {
  const body = Object.keys(light)
    .map((name) => `  --color-${name}: var(--rc-${name});`)
    .join('\n');
  return `@theme inline {\n${body}\n}`;
}

function systemDarkModeBlock(): string {
  const nested = semanticBlock(':root:not([data-theme="light"])', dark, NESTED_INDENT);
  return `@media (prefers-color-scheme: dark) {\n${nested}\n}`;
}

function semanticColorBlocks(): string[] {
  return [
    semanticBlock(':root', light),
    systemDarkModeBlock(),
    semanticBlock(':root[data-theme="dark"]', dark),
    SCOPED_PREVIEWS_NOTE,
    semanticBlock(':where(:root) [data-theme="light"]', light),
    semanticBlock(':where(:root) [data-theme="dark"]', dark),
  ];
}

/** Tailwind CSS v4 stylesheet with the brand theme and light and dark semantic colors. */
export function buildCss(): string {
  const sections = [
    GENERATED_HEADER,
    themeBlock(),
    semanticThemeBlock(),
    ...semanticColorBlocks(),
    ...COLOR_SCHEME_RULES,
    '',
  ];
  return sections.join(SECTION_SEPARATOR);
}
